function remedyByPrefix(code: string): string {
  if (code.startsWith("P03")) {
    return "Пропуски: свечи/катушки/форсунки, компрессия, подсос, топливное давление. Найти проблемный цилиндр по счётчикам.";
  }
  if (code.startsWith("P07") || code.startsWith("P17")) {
    return "Трансмиссия: температурa и уровень ATF/CVTF, коды TCM, соленоиды, CAN до TCM. Не игнорировать перегрев.";
  }
  if (code.startsWith("P02") && code.includes("34")) {
    return "Турбо: утечки наддува, wastegate, датчики давления, состояние масла турбины.";
  }
  if (code.startsWith("C0")) {
    return "Шасси: датчики колёс, ABS-кольца, проводка, калибровка G-сенсора/VDC после работ по подвеске.";
  }
  if (code.startsWith("B1") || code.startsWith("B0")) {
    return "Кузов: CAN, питание BIU/ETACS, разъёмы после ремонта; сверить с кодами U01xx/U04xx.";
  }
  if (code.startsWith("U01")) {
    return "CAN: проверить питание и разъёмы блока-источника, обрыв CAN-H/L, коррозию, недавние отключения АКБ.";
  }
  if (code.startsWith("U04")) {
    return "Сначала устранить коды блока-источника; проверить CAN и качество сигнала (не только «нет связи»).";
  }
  if (code.startsWith("P1")) {
    return "Заводской код марки: искать расшифровку по модели/году в TSB или сервисной литературе; проверить связанные P0/U-коды.";
  }
  return "Уточнить код по сервис-мануалу модели; проверить сопутствующие коды, freeze frame и live-данные блока.";
}

export function remedyForDtcCode(code: string): string {
  const clean = code.trim().toUpperCase();
  return EXACT_DTC_REMEDY_RU[clean] ?? remedyByPrefix(clean);
}

export function describeDtcFull(code: string): { description: string; remedy: string } {
  return {
    description: describeDtcCode(code),
    remedy: remedyForDtcCode(code),
  };
}
