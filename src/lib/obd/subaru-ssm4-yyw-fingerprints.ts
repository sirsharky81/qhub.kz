export function fingerprintFromEyesightDids(didHexById: Record<string, string>): string {
  return SSM4_YYW_FP_DID_KEYS.map((k) => {
    const raw = (didHexById[k] ?? didHexById[k.toLowerCase()] ?? "").trim().toUpperCase();
    const tok = (raw.split(/\s+/)[0] ?? "").slice(0, 2);
    return tok.length === 2 ? tok : "__";
  }).join("");
}

function packMatch(
  hits: readonly Ssm4YywFingerprint[],
  fp: string,
): { optionCode: string; appliedModel: string | null; unique: boolean; candidates: string[]; fp: string } | null {
  if (!hits.length) return null;
  const opts = [...new Set(hits.map((p) => p.optionCode))];
  const apps = [...new Set(hits.map((p) => p.appliedModel))];
  return {
    optionCode: opts[0]!,
    appliedModel: apps.length === 1 ? apps[0]! : null,
    unique: opts.length === 1 && apps.length === 1,
    candidates: [...new Set(hits.map((p) => `${p.appliedModel}+${p.optionCode}`))],
    fp,
  };
}

/** Reverse-lookup from EyeSight 35xx dump (Applied known → Option; or global). */
export function matchSsm4OptionFromEyesightDids(
  appliedModel: string | null | undefined,
  didHexById: Record<string, string>,
): { optionCode: string; appliedModel: string | null; unique: boolean; candidates: string[]; fp: string } | null {
  const fp = fingerprintFromEyesightDids(didHexById);
  if (!fp.includes("0") && !fp.includes("F") && !/[A-E1-9]/.test(fp)) return null;
  const app = appliedModel?.trim().toUpperCase() || "";
  if (app) {
    const list = byModel.get(app) ?? [];
    const exact = list.filter((p) => p.fp === fp);
    if (exact.length) return packMatch(exact, fp);
    const partial = list.filter((p) => {
      for (let i = 0; i < SSM4_YYW_FP_DID_KEYS.length; i++) {
        const got = fp.slice(i * 2, i * 2 + 2);
        const want = p.fp.slice(i * 2, i * 2 + 2);
        if (got === "__" || !want) continue;
        if (got !== want) return false;
      }
      return SSM4_YYW_FP_DID_KEYS.some((_, i) => {
        const got = fp.slice(i * 2, i * 2 + 2);
        return got !== "__" && Boolean(got);
      });
    });
    return packMatch(partial, fp);
  }
  return packMatch(byFp.get(fp) ?? [], fp);
}

/** Destination hint from EyeSight DID 3502 (20≈US, 30≈CA for BTA stereo). */
export function eyesightDestinationHintFrom3502(byteHex: string | null | undefined): "USA" | "CANADA" | "UNKNOWN" {
  const b = (byteHex ?? "").trim().toUpperCase().slice(0, 2);
  if (b === "20") return "USA";
  if (b === "30") return "CANADA";
  return "UNKNOWN";
}
