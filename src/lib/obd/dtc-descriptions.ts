export function describeDtcCode(code: string): string {
  const clean = code.trim().toUpperCase();
  const exact = EXACT_DTC_RU[clean];
  if (exact) return exact;

  if (clean.startsWith("U01") || clean.startsWith("U11")) {
    return "Потеря связи по шине CAN с одним из электронных блоков";
  }
  if (clean.startsWith("U04") || clean.startsWith("U14")) {
    return "Получены недостоверные данные по шине CAN от смежного блока";
  }
  if (clean.startsWith("P030")) {
    return "Пропуски воспламенения в цилиндрах";
  }
  if (clean.startsWith("P013") || clean.startsWith("P014") || clean.startsWith("P015") || clean.startsWith("P016")) {
    return "Цепь кислородного датчика (лямбда-зонда) или его подогрева";
  }
  if (clean.startsWith("P07") || clean.startsWith("P08") || clean.startsWith("P17")) {
    return "Код трансмиссии (АКПП / вариатор)";
  }
  if (clean.startsWith("C")) {
    return "Код шасси (ABS / VDC / ASC / тормозная система)";
  }
  if (clean.startsWith("B")) {
    return "Код кузовной электроники (ETACS / BIU / климат / SRS)";
  }
  if (clean.startsWith("P1")) {
    return "Заводской код двигателя/трансмиссии (специфичен для марки)";
  }
  return "Стандартный диагностический код SAE J2012";
}
