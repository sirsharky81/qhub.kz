const I18nContext = createContext<{ locale: QrLocale; t: (key: string) => string }>({
  locale: "ru",
  t: (key) => ru[key] ?? key,
});

export function QrI18nProvider({
  locale,
  children,
}: {
  locale: QrLocale;
  children: ReactNode;
}) {
  const value = useMemo(
    () => ({
      locale,
      t: (key: string) => qrMessages[locale][key] ?? qrMessages.ru[key] ?? key,
    }),
    [locale],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useQrTranslations() {
  return useContext(I18nContext);
}

export function typeLabel(type: QrType, t: (key: string) => string): string {
  return t(`type.${type}`);
}

export function typeHint(type: QrType, t: (key: string) => string): string {
  return t(`hint.${type}`);
}
