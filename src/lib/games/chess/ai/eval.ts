const TABLES: Record<ChessPieceType, number[]> = {
  p: PAWN_PST,
  n: KNIGHT_PST,
  b: BISHOP_PST,
  r: ROOK_PST,
  q: QUEEN_PST,
  k: KING_PST,
};

export function evaluateBoard(chess: Chess): number {
  let score = 0;
  const board = chess.board();
  for (let rank = 0; rank < 8; rank += 1) {
    for (let file = 0; file < 8; file += 1) {
      const piece = board[rank]![file];
      if (!piece) continue;
      const whiteIndex = (7 - rank) * 8 + file;
      const blackIndex = rank * 8 + file;
      const index = piece.color === "w" ? whiteIndex : blackIndex;
      const value = PIECE_VALUE[piece.type] + (TABLES[piece.type][index] ?? 0);
      score += piece.color === "w" ? value : -value;
    }
  }
  return chess.turn() === "w" ? score : -score;
}

export function pieceValue(type: ChessPieceType): number {
  return PIECE_VALUE[type];
}
